// Compiles contracts/SwapSimulator.sol with solc-js and writes its runtime bytecode to src/simulator.ts, so the
// skill itself never needs a compiler. Run with `npm run compile` after changing the contract.
import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync(new URL("./contracts/SwapSimulator.sol", import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: { "SwapSimulator.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["evm.deployedBytecode.object"] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
const code = out.contracts["SwapSimulator.sol"].SwapSimulator.evm.deployedBytecode.object;
writeFileSync(
  new URL("./src/simulator.ts", import.meta.url),
  `// Generated by compile.mjs from contracts/SwapSimulator.sol (solc ${solc.version()}). Do not edit.\nexport const SIMULATOR_CODE = "0x${code}" as const;\n`,
);
console.log(`SwapSimulator runtime: ${code.length / 2} bytes`);
